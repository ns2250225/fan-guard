import { invoke } from "@tauri-apps/api/core";
import type {
  DiagnosisReport,
  FileInfo,
  HistoryData,
  HwNode,
  KillMode,
  KillPreview,
  KillResult,
  Marker,
  ProcessDetail,
  SensorStatus,
  Settings,
  SignatureInfo,
  Snapshot,
  StaticInfo,
  SysPoint,
  ThreadInfo,
} from "./types";

export const api = {
  staticInfo: () => invoke<StaticInfo>("get_static_info"),
  snapshot: () => invoke<Snapshot | null>("get_snapshot"),
  realtime: () => invoke<{ points: SysPoint[]; markers: Marker[] }>("get_realtime"),
  settings: () => invoke<Settings>("get_settings"),
  saveSettings: (settings: Settings) => invoke<Settings>("save_settings", { settings }),
  setWhitelist: (name: string, add: boolean) => invoke<Settings>("set_whitelist", { name, add }),
  setPaused: (paused: boolean) => invoke<void>("set_paused", { paused }),
  getPaused: () => invoke<boolean>("get_paused"),
  refreshNow: () => invoke<void>("refresh_now"),
  processDetail: (pid: number, createTime: string, withFile: boolean) =>
    invoke<ProcessDetail>("get_process_detail", { pid, createTime, withFile }),
  threads: (pid: number, createTime: string) => invoke<ThreadInfo[]>("get_process_threads", { pid, createTime }),
  signature: (path: string) => invoke<SignatureInfo>("get_signature", { path }),
  fileInfo: (path: string) => invoke<FileInfo>("get_file_info", { path }),
  openFileLocation: (path: string) => invoke<void>("open_file_location", { path }),
  showFileProperties: (path: string) => invoke<void>("show_file_properties", { path }),
  previewKill: (pid: number, createTime: string) => invoke<KillPreview>("preview_kill", { pid, createTime }),
  kill: (pid: number, createTime: string, mode: KillMode) =>
    invoke<KillResult>("kill_process", { pid, createTime, mode }),
  diagnose: () => invoke<DiagnosisReport>("run_diagnosis"),
  ignoreAnomalies: (code?: string) => invoke<void>("ignore_anomalies", { code: code ?? null }),
  history: (range: string) => invoke<HistoryData>("get_history", { range }),
  exportCsv: (kind: string, range: string, path: string) => invoke<number>("export_csv", { kind, range, path }),
  clearHistory: () => invoke<void>("clear_history"),
  sensorRaw: () => invoke<HwNode[]>("get_sensor_raw"),
  sensorStatus: () => invoke<SensorStatus>("get_sensor_status"),
  isElevated: () => invoke<boolean>("is_elevated"),
  relaunchAdmin: () => invoke<void>("relaunch_admin"),
  quit: () => invoke<void>("quit_app"),
  closeWindow: () => invoke<void>("close_window"),
  hwinfoLaunch: () => invoke<void>("hwinfo_launch"),
  hwinfoImport: (path: string) => invoke<string>("hwinfo_import", { path }),
  hwinfoOpenDownload: () => invoke<void>("hwinfo_open_download"),
};
